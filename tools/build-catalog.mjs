// Builds content/catalog.js: the names of every Explore scene and research method (EN + HE), read straight
// from the level files, so the search box can find scenes without loading any 3D code.
// Run after adding or renaming a scene:   node tools/build-catalog.mjs
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

// The level files only touch the browser inside their build() functions; these stubs let them load in Node.
globalThis.document ??= { createElement: () => ({ getContext: () => null }) };
globalThis.window ??= { addEventListener() {}, innerWidth: 1280, innerHeight: 800 };

const root = path.resolve('.');
const { LEVELS, METHODS_LEVEL } = await import(pathToFileURL(path.join(root, 'src/visual/levels/index.js')).href);
const scenes = [];
for (const L of [...LEVELS.filter((l) => l.load), METHODS_LEVEL]) {
  const mod = (await L.load()).default;
  for (const s of mod.scenes) {
    scenes.push({ level: L.id, id: s.id, icon: s.icon || L.icon, name: s.name, intro: s.intro || null });
  }
}
const out = `// Generated by tools/build-catalog.mjs — do not edit by hand (run the tool again after changing a scene).
export const SCENES = ${JSON.stringify(scenes, null, 1)};
`;
fs.writeFileSync(path.join(root, 'content/catalog.js'), out);
console.log(`content/catalog.js: ${scenes.length} scenes`);
